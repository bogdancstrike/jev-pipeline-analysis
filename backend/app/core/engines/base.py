"""Engine contract: a named model backend that modules use through a narrow port.

Engines are declared in `config/engines.yaml`; a module's YAML picks one with `engine:`.
Replacing the model behind a task = pointing that module at another engine name.

Ports (an engine implements the ones its model can do):
* `classify(texts, question)` -> one `Classification` per text. Every engine kind has it, so
  any label module (topic, sentiment, risk, ...) can run on any engine.
* `ask(state, question)` -> a raw `/v1/systemone` answer (yes/no over structured states):
  decision engines only.
* `extract(task, texts, spec)` -> entities / relations / classification / structured fields:
  extraction engines only (GLiNER2).
"""
import os
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from ..config import Settings
from ..metrics import CallMetrics


class EngineError(RuntimeError):
    pass


@dataclass(frozen=True)
class Question:
    """A closed question. `criteria`: choice -> {option: description}; noul -> {"true", "false"}."""
    key: str
    type: Literal["choice", "noul"]
    instructions: str
    criteria: dict[str, str] = field(default_factory=dict)

    def payload(self, names_only: bool = False) -> dict:
        if self.type == "choice":
            crit = {k: None if names_only else (v or None) for k, v in self.criteria.items()}
        else:
            crit = self.criteria or None
        return {"type": self.type, "instructions": self.instructions, "criteria": crit}


@dataclass
class Classification:
    label: str
    confidence: float
    probabilities: dict[str, float] = field(default_factory=dict)
    chunks: int = 1


def read_secret(settings: Settings, name: str | None) -> str:
    """An API key from `<secrets_dir>/<name>` (generated by secrets-init) or env `<NAME>`."""
    if not name:
        return ""
    if v := os.environ.get(name.upper()):
        return v
    path = Path(os.environ.get("SECRETS_DIR", "/run/secrets")) / name
    return path.read_text().strip() if path.is_file() else ""


class Engine(ABC):
    kind: str

    def __init__(self, name: str, cfg: dict[str, Any], settings: Settings):
        self.name, self.cfg, self.settings = name, cfg, settings
        self.ready = False
        self.info: dict[str, Any] = {}
        self.metrics = CallMetrics()
        self.description = str(cfg.get("description", ""))

    @abstractmethod
    async def wait_ready(self) -> None: ...

    @abstractmethod
    async def aclose(self) -> None: ...

    def status(self) -> dict[str, Any]:
        return {"name": self.name, "kind": self.kind, "ready": self.ready,
                "description": self.description, **self.info}

    async def refresh(self) -> None:
        """Re-check runtime state (e.g. a silent CPU fallback). Default: nothing to check."""

    @abstractmethod
    async def classify(self, texts: list[str], q: Question, options: dict[str, Any] | None = None
                       ) -> list[Classification | None]: ...

    async def ask(self, state: dict, q: Question, options: dict[str, Any] | None = None) -> dict:
        raise EngineError(f"engine {self.name!r} ({self.kind}) cannot answer free-form state questions")

    async def extract(self, task: str, texts: list[str], spec: Any, options: dict[str, Any] | None = None
                      ) -> list[Any]:
        raise EngineError(f"engine {self.name!r} ({self.kind}) cannot extract {task}")
